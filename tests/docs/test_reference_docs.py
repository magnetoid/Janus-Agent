"""The website reference docs keep up with the code (backlog P2).

The whole self-learning command family once shipped with no entry in the
CLI reference, and several pages existed that no sidebar linked to. These
tests tie the docs to their sources of truth: the parser's builtin
subcommands, ``COMMAND_REGISTRY``, and ``website/sidebars.ts``.
"""

import re
from pathlib import Path

_REPO = Path(__file__).resolve().parents[2]
_DOCS = _REPO / "website" / "docs"

# Builtin names that are not user-facing commands of their own.
_CLI_UNDOCUMENTED = {
    "help",  # argparse help, not a command
    "gui",   # alias of `janus desktop`, documented with it
}

# Pages deliberately outside the sidebar, each with the reason.
_UNLISTED_PAGES = {
    "index",                              # the landing page (`slug: /`)
    "user-guide/skills/godmode",          # superseded by skills/bundled/red-teaming
    "user-guide/skills/google-workspace",  # superseded by skills/bundled/productivity
}


def _read(rel):
    return (_REPO / rel).read_text(encoding="utf-8")


def test_every_builtin_subcommand_is_in_the_cli_reference():
    from janus_cli.main import _BUILTIN_SUBCOMMANDS

    doc = _read("website/docs/reference/cli-commands.md")
    missing = sorted(
        name for name in _BUILTIN_SUBCOMMANDS - _CLI_UNDOCUMENTED
        if not re.search(r"`janus %s\b" % re.escape(name), doc)
    )
    assert missing == [], f"add these to website/docs/reference/cli-commands.md: {missing}"


def test_every_registered_slash_command_is_in_the_slash_reference():
    from janus_cli.commands import COMMAND_REGISTRY

    doc = _read("website/docs/reference/slash-commands.md")
    missing = sorted(
        cmd.name for cmd in COMMAND_REGISTRY
        if not re.search(r"`/%s\b" % re.escape(cmd.name), doc)
    )
    assert missing == [], f"add these to website/docs/reference/slash-commands.md: {missing}"


def _doc_id(path):
    doc_id = path.relative_to(_DOCS).with_suffix("").as_posix()
    front = re.match(r"---\n(.*?)\n---", path.read_text(encoding="utf-8"), re.S)
    if front:
        explicit = re.search(r"^id:\s*(\S+)", front.group(1), re.M)
        if explicit:
            doc_id = (Path(doc_id).parent / explicit.group(1)).as_posix()
    return doc_id


def test_every_docs_page_is_reachable_from_the_sidebar():
    sidebar = _read("website/sidebars.ts")
    referenced = set(re.findall(r"['\"]([A-Za-z0-9_./-]+)['\"]", sidebar))
    autogenerated = re.findall(r"dirName:\s*['\"]([^'\"]+)['\"]", sidebar)

    orphans = []
    for path in sorted(_DOCS.rglob("*")):
        if path.suffix not in (".md", ".mdx"):
            continue
        doc_id = _doc_id(path)
        if doc_id in referenced or doc_id in _UNLISTED_PAGES:
            continue
        if any(doc_id.startswith(d.rstrip("/") + "/") for d in autogenerated):
            continue
        orphans.append(doc_id)
    assert orphans == [], f"link these from website/sidebars.ts (or list them in _UNLISTED_PAGES): {orphans}"


def test_unlisted_pages_still_exist():
    # A stale allow-list entry would silently hide a future orphan.
    ids = {_doc_id(p) for p in _DOCS.rglob("*") if p.suffix in (".md", ".mdx")}
    assert _UNLISTED_PAGES <= ids
